export function SharePopover({ title, url }: SharePopoverProps) {
  const [copied, setCopied] = useState(false);
  const shareUrl = url || (typeof window !== "undefined" ? window.location.href : "");

  const handleCopyLink = () => {
    navigator.clipboard.writeText(shareUrl);
    setCopied(true);
    toast.success("Link copied to clipboard");
    setTimeout(() => setCopied(false), 2000);
  };

  const handleShare = (platform: typeof socialPlatforms[0]) => {
    if (platform.onClick) {
      platform.onClick(shareUrl);
      return;
    }
    window.open(platform.getUrl(shareUrl, title), "_blank", "width=600,height=400");
  };

  return (
    <Popover>
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          size="icon"
          className="rounded-full border-white/20 bg-white/10 backdrop-blur-sm hover:bg-white/20"
        >
          <Share2 className="w-5 h-5" />
        </Button>
      </PopoverTrigger>
      <PopoverContent className="w-72 p-4" align="center">
        <div className="space-y-4">
          <h4 className="font-medium text-sm text-center">Share</h4>
          
          <div className="grid grid-cols-3 gap-3">
            {socialPlatforms.map((platform) => (
              <button
                key={platform.name}
                onClick={() => handleShare(platform)}
                className={`flex flex-col items-center gap-1.5 p-3 rounded-lg bg-muted/50 transition-colors ${platform.color}`}
              >
                {platform.icon}
                <span className="text-xs">{platform.name}</span>
              </button>
            ))}
          </div>

          <div className="flex items-center gap-2 pt-2 border-t border-border">
            <input
              type="text"
              value={shareUrl}
              readOnly
              className="flex-1 text-xs bg-muted/50 rounded px-2 py-1.5 truncate"
            />
            <Button
              variant="ghost"
              size="sm"
              onClick={handleCopyLink}
              className="shrink-0"
            >
              {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
            </Button>
          </div>
        </div>
      </PopoverContent>
    </Popover>
  );
}
